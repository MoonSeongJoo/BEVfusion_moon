def _find_leaf_dataset(
    dataloader_cfg,
):

    dataset_cfg = (
        dataloader_cfg[
            'dataset'
        ]
    )

    while (
        isinstance(
            dataset_cfg,
            dict,
        )
        and 'pipeline'
        not in dataset_cfg
        and 'dataset'
        in dataset_cfg
    ):
        dataset_cfg = (
            dataset_cfg[
                'dataset'
            ]
        )

    return dataset_cfg


def _patch_pcc_depth_transform(
    dataloader_cfg,
    deterministic,
    debug=False,
):

    dataset_cfg = (
        _find_leaf_dataset(
            dataloader_cfg
        )
    )

    found = False

    for t in dataset_cfg[
        'pipeline'
    ]:

        if (
            t.get('type')
            == 'PointToMultiViewDepth'
        ):

            t['max_r'] = 10.0
            t['max_t'] = 0.75

            t[
                'deterministic_perturb'
            ] = deterministic

            t[
                'perturb_seed'
            ] = 20260811

            t[
                'debug_calib_consistency'
            ] = debug

            found = True

    if not found:

        raise RuntimeError(
            'PointToMultiViewDepth '
            'not found in pipeline'
        )


